BEGIN;

-- ============================================================================
-- SECTION 1: CANONICAL TABLES FOR OTPs AND PASSWORD RESET REQUESTS
-- ============================================================================

-- 1.1 Secure Single-Use OTP Storage Table
-- Note: code_hash stores a 64-character hex HMAC-SHA256 digest generated by the trusted Edge Function
-- using a dedicated server secret (OTP_HMAC_SECRET). Plaintext codes are never stored.
CREATE TABLE IF NOT EXISTS public.account_otps (
    id UUID PRIMARY KEY DEFAULT extensions.gen_random_uuid(),
    application_id UUID REFERENCES public.account_applications(id) ON DELETE CASCADE,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT NOT NULL,
    code_hash TEXT NOT NULL CHECK (code_hash ~* '^[0-9a-f]{64}$'), -- Exactly 64 hex characters
    code_type TEXT NOT NULL CHECK (code_type IN ('ACTIVATION', 'PASSWORD_RESET')),
    status TEXT NOT NULL DEFAULT 'ISSUED' CHECK (status IN ('ISSUED', 'VERIFIED', 'COMPLETED', 'EXPIRED', 'SUPERSEDED', 'MAX_ATTEMPTS_EXCEEDED')),
    attempts_count INT NOT NULL DEFAULT 0,
    max_attempts INT NOT NULL DEFAULT 5,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT pg_catalog.now(),
    verified_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ
);

ALTER TABLE public.account_otps ENABLE ROW LEVEL SECURITY;

-- 1.2 System Owner-Approved Password Reset Requests Table
CREATE TABLE IF NOT EXISTS public.password_reset_requests (
    id UUID PRIMARY KEY DEFAULT extensions.gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    organization_id UUID REFERENCES public.organizations(id) ON DELETE CASCADE,
    email TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'COMPLETED')),
    reason TEXT,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT pg_catalog.now(),
    reviewed_at TIMESTAMPTZ,
    reviewed_by UUID REFERENCES auth.users(id) ON DELETE SET NULL
);

ALTER TABLE public.password_reset_requests ENABLE ROW LEVEL SECURITY;

-- ============================================================================
-- SECTION 2: INDEXES FOR FAST LOOKUPS & CONCURRENCY
-- ============================================================================

CREATE INDEX IF NOT EXISTS idx_account_otps_lookup
ON public.account_otps (email, code_type, status);

CREATE INDEX IF NOT EXISTS idx_password_reset_requests_user
ON public.password_reset_requests (user_id, status);

-- ============================================================================
-- SECTION 3: PRIVILEGES AND ROW LEVEL SECURITY POLICIES
-- ============================================================================

-- 3.1 account_otps: Service Role Exclusive
REVOKE ALL ON public.account_otps FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.account_otps TO service_role;

-- 3.2 password_reset_requests: Strict Privilege Isolation
-- Ordinary authenticated users can ONLY SELECT their own requests and INSERT new ones for themselves.
-- Ordinary authenticated users CANNOT update status, reviewed_at, or reviewed_by.
REVOKE ALL ON public.password_reset_requests FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.password_reset_requests TO authenticated;
GRANT INSERT (user_id, organization_id, email, reason) ON public.password_reset_requests TO authenticated;
GRANT ALL ON public.password_reset_requests TO service_role;

-- RLS Policy: Users insert ONLY their own password reset requests matching their active profile
DROP POLICY IF EXISTS "Users insert own password_reset_requests" ON public.password_reset_requests;
CREATE POLICY "Users insert own password_reset_requests" ON public.password_reset_requests
    FOR INSERT TO authenticated WITH CHECK (
        user_id = auth.uid()
        AND EXISTS (
            SELECT 1 FROM public.profiles p
            WHERE p.id = auth.uid()
              AND p.account_status = 'active'
              AND (password_reset_requests.organization_id IS NULL OR p.organization_id = password_reset_requests.organization_id)
        )
    );

-- RLS Policy: Users read own password reset requests
DROP POLICY IF EXISTS "Users read own password_reset_requests" ON public.password_reset_requests;
CREATE POLICY "Users read own password_reset_requests" ON public.password_reset_requests
    FOR SELECT USING (user_id = auth.uid());

-- RLS Policy: System Owners read all password reset requests
DROP POLICY IF EXISTS "System Owners read password_reset_requests" ON public.password_reset_requests;
CREATE POLICY "System Owners read password_reset_requests" ON public.password_reset_requests
    FOR SELECT USING (public.is_system_owner());

-- RLS Policy: System Owners update status and notes on password reset requests
DROP POLICY IF EXISTS "System Owners update password_reset_requests" ON public.password_reset_requests;
CREATE POLICY "System Owners update password_reset_requests" ON public.password_reset_requests
    FOR UPDATE USING (public.is_system_owner()) WITH CHECK (public.is_system_owner());

-- ============================================================================
-- SECTION 4: SERVER-SIDE TRANSACTIONAL HELPER RPCs (SERVICE ROLE EXCLUSIVE)
-- ============================================================================

-- 4.1 RPC: issue_account_otp
-- Action: Locks parent entity row (FOR UPDATE), verifies activation / reset eligibility,
--         supersedes prior active codes, inserts new OTP record, and writes audit log.
CREATE OR REPLACE FUNCTION public.issue_account_otp(
    p_application_id UUID,
    p_user_id UUID,
    p_email TEXT,
    p_code_hash TEXT,
    p_code_type TEXT,
    p_ttl_minutes INT DEFAULT 30
)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_otp_id UUID;
    v_clean_email TEXT;
    v_app RECORD;
    v_profile RECORD;
    v_reset_req RECORD;
    v_actor_id UUID;
BEGIN
    v_clean_email := LOWER(TRIM(COALESCE(p_email, '')));
    IF v_clean_email = '' OR p_code_hash IS NULL OR TRIM(p_code_hash) !~* '^[0-9a-f]{64}$' THEN
        RAISE EXCEPTION 'Validation failed: Email and valid 64-character hex HMAC code_hash are required.';
    END IF;

    IF p_code_type NOT IN ('ACTIVATION', 'PASSWORD_RESET') THEN
        RAISE EXCEPTION 'Validation failed: Invalid code_type.';
    END IF;

    IF p_ttl_minutes < 5 OR p_ttl_minutes > 60 THEN
        RAISE EXCEPTION 'Validation failed: p_ttl_minutes must be between 5 and 60 minutes.';
    END IF;

    -- Validate target account association and eligibility under row locking
    IF p_code_type = 'ACTIVATION' THEN
        IF p_application_id IS NULL THEN
            RAISE EXCEPTION 'Validation failed: p_application_id is required for ACTIVATION codes.';
        END IF;

        -- Lock parent application row FOR UPDATE to serialize concurrent issuance requests
        SELECT * INTO v_app
        FROM public.account_applications
        WHERE id = p_application_id
        FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Validation failed: Referenced application_id does not exist.';
        END IF;

        -- Activation OTP issuance requires approved status, provisioned organization, and created Auth user
        IF v_app.status <> 'APPROVED' THEN
            RAISE EXCEPTION 'Validation failed: Application is not approved for activation (current status: %).', v_app.status;
        END IF;

        IF v_app.organization_id IS NULL THEN
            RAISE EXCEPTION 'Validation failed: Organization has not been provisioned for this application.';
        END IF;

        IF v_app.auth_user_id IS NULL THEN
            RAISE EXCEPTION 'Validation failed: Auth user account has not been mapped for this application.';
        END IF;

        IF LOWER(TRIM(v_app.email)) <> v_clean_email THEN
            RAISE EXCEPTION 'Validation failed: Application email does not match requested email.';
        END IF;

        -- Identify actor for audit logging (System Owner who claimed application)
        SELECT claimed_by INTO v_actor_id
        FROM public.approval_claims
        WHERE application_id = p_application_id;

        IF v_actor_id IS NULL THEN
            v_actor_id := v_app.auth_user_id;
        END IF;

    ELSIF p_code_type = 'PASSWORD_RESET' THEN
        IF p_user_id IS NULL THEN
            RAISE EXCEPTION 'Validation failed: p_user_id is required for PASSWORD_RESET codes.';
        END IF;

        -- Lock parent profile row FOR UPDATE to serialize concurrent issuance requests
        SELECT p.*, LOWER(TRIM(u.email)) AS user_email INTO v_profile
        FROM public.profiles p
        JOIN auth.users u ON p.id = u.id
        WHERE p.id = p_user_id
        FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Validation failed: Referenced user_id does not exist in profiles/auth.users.';
        END IF;

        IF v_profile.account_status <> 'active' THEN
            RAISE EXCEPTION 'Validation failed: Account status is not active (current status: %).', v_profile.account_status;
        END IF;

        IF v_profile.user_email <> v_clean_email THEN
            RAISE EXCEPTION 'Validation failed: Registered user email does not match requested email.';
        END IF;

        -- Require an existing password_reset_request explicitly APPROVED by System Owner
        SELECT * INTO v_reset_req
        FROM public.password_reset_requests
        WHERE user_id = p_user_id
          AND LOWER(email) = v_clean_email
          AND status = 'APPROVED'
        ORDER BY requested_at DESC
        LIMIT 1;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Validation failed: No System Owner-approved password reset request found for this user.';
        END IF;

        IF v_profile.organization_id IS DISTINCT FROM v_reset_req.organization_id THEN
            RAISE EXCEPTION 'Validation failed: Approved reset request organization does not match user profile organization.';
        END IF;

        v_actor_id := COALESCE(v_reset_req.reviewed_by, p_user_id);
    END IF;

    -- Supersede older active codes for this email and code_type
    UPDATE public.account_otps
    SET status = 'SUPERSEDED'
    WHERE LOWER(email) = v_clean_email
      AND code_type = p_code_type
      AND status = 'ISSUED';

    -- Insert new OTP record
    INSERT INTO public.account_otps (
        application_id,
        user_id,
        email,
        code_hash,
        code_type,
        status,
        expires_at
    ) VALUES (
        p_application_id,
        p_user_id,
        v_clean_email,
        TRIM(p_code_hash),
        p_code_type,
        'ISSUED',
        pg_catalog.now() + (p_ttl_minutes || ' minutes')::INTERVAL
    )
    RETURNING id INTO v_otp_id;

    -- Write audit log entry with valid Auth user actor_id
    IF v_actor_id IS NOT NULL THEN
        INSERT INTO public.audit_logs (
            actor_id,
            action,
            table_name,
            record_id,
            details
        ) VALUES (
            v_actor_id,
            'ISSUE_ACCOUNT_OTP',
            'account_otps',
            v_otp_id,
            jsonb_build_object('email', v_clean_email, 'code_type', p_code_type, 'ttl_minutes', p_ttl_minutes)
        );
    END IF;

    RETURN v_otp_id;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.issue_account_otp(UUID, UUID, TEXT, TEXT, TEXT, INT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.issue_account_otp(UUID, UUID, TEXT, TEXT, TEXT, INT) TO service_role;

-- 4.2 RPC: verify_account_otp
-- Action: Validates an OTP code HMAC digest against the database under FOR UPDATE row locking, enforcing single-use, TTL, attempt limits, and audit logging
CREATE OR REPLACE FUNCTION public.verify_account_otp(
    p_email TEXT,
    p_code_hash TEXT,
    p_code_type TEXT
)
RETURNS TABLE(success BOOLEAN, otp_id UUID, application_id UUID, user_id UUID, error_message TEXT)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_record RECORD;
    v_clean_email TEXT;
    v_actor_id UUID;
BEGIN
    v_clean_email := LOWER(TRIM(COALESCE(p_email, '')));
    IF v_clean_email = '' OR p_code_hash IS NULL OR LENGTH(TRIM(p_code_hash)) < 32 THEN
        RETURN QUERY SELECT FALSE, NULL::UUID, NULL::UUID, NULL::UUID, 'Validation failed: Email and valid HMAC code_hash are required.'::TEXT;
        RETURN;
    END IF;

    -- Find active ISSUED or VERIFIED OTP record for this email and code_type (locked FOR UPDATE)
    SELECT * INTO v_record
    FROM public.account_otps
    WHERE LOWER(email) = v_clean_email
      AND code_type = p_code_type
      AND status IN ('ISSUED', 'VERIFIED')
    ORDER BY created_at DESC
    LIMIT 1
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN QUERY SELECT FALSE, NULL::UUID, NULL::UUID, NULL::UUID, 'Invalid or expired single-use code.'::TEXT;
        RETURN;
    END IF;

    -- If already VERIFIED, allow password update recovery window if within TTL
    IF v_record.status = 'VERIFIED' THEN
        IF v_record.expires_at < pg_catalog.now() THEN
            UPDATE public.account_otps SET status = 'EXPIRED' WHERE id = v_record.id;
            RETURN QUERY SELECT FALSE, v_record.id, v_record.application_id, v_record.user_id, 'Verification session expired. Please request a new code.'::TEXT;
            RETURN;
        END IF;

        -- Return existing verified record details to support recovery retry
        RETURN QUERY SELECT TRUE, v_record.id, v_record.application_id, v_record.user_id, NULL::TEXT;
        RETURN;
    END IF;

    -- Check Expiration TTL
    IF v_record.expires_at < pg_catalog.now() THEN
        UPDATE public.account_otps SET status = 'EXPIRED' WHERE id = v_record.id;
        RETURN QUERY SELECT FALSE, v_record.id, v_record.application_id, v_record.user_id, 'The single-use code has expired. Please request a new code.'::TEXT;
        RETURN;
    END IF;

    -- Check Max Failed Attempts
    IF v_record.attempts_count >= v_record.max_attempts THEN
        UPDATE public.account_otps SET status = 'MAX_ATTEMPTS_EXCEEDED' WHERE id = v_record.id;
        RETURN QUERY SELECT FALSE, v_record.id, v_record.application_id, v_record.user_id, 'Maximum verification attempts exceeded. Please request a new code.'::TEXT;
        RETURN;
    END IF;

    -- Verify HMAC Code Hash
    IF v_record.code_hash <> TRIM(p_code_hash) THEN
        UPDATE public.account_otps
        SET attempts_count = attempts_count + 1,
            status = CASE WHEN attempts_count + 1 >= max_attempts THEN 'MAX_ATTEMPTS_EXCEEDED' ELSE 'ISSUED' END
        WHERE id = v_record.id;

        RETURN QUERY SELECT FALSE, v_record.id, v_record.application_id, v_record.user_id, 'Incorrect code. Please check and try again.'::TEXT;
        RETURN;
    END IF;

    -- Successful Verification: Mark Single-Use Code as VERIFIED
    UPDATE public.account_otps
    SET status = 'VERIFIED',
        verified_at = pg_catalog.now()
    WHERE id = v_record.id;

    -- Determine valid Auth actor ID for audit logging
    v_actor_id := COALESCE(v_record.user_id, (SELECT auth_user_id FROM public.account_applications WHERE id = v_record.application_id));

    IF v_actor_id IS NOT NULL THEN
        INSERT INTO public.audit_logs (
            actor_id,
            action,
            table_name,
            record_id,
            details
        ) VALUES (
            v_actor_id,
            'VERIFY_ACCOUNT_OTP',
            'account_otps',
            v_record.id,
            jsonb_build_object('email', v_clean_email, 'code_type', p_code_type, 'status', 'VERIFIED')
        );
    END IF;

    RETURN QUERY SELECT TRUE, v_record.id, v_record.application_id, v_record.user_id, NULL::TEXT;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.verify_account_otp(TEXT, TEXT, TEXT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.verify_account_otp(TEXT, TEXT, TEXT) TO service_role;

-- 4.3 RPC: complete_account_otp
-- Action: Marks a VERIFIED OTP code as COMPLETED after password update succeeds in Supabase Auth Edge Function
CREATE OR REPLACE FUNCTION public.complete_account_otp(
    p_otp_id UUID
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    UPDATE public.account_otps
    SET status = 'COMPLETED',
        completed_at = pg_catalog.now()
    WHERE id = p_otp_id AND status = 'VERIFIED';

    RETURN FOUND;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.complete_account_otp(UUID) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.complete_account_otp(UUID) TO service_role;

COMMIT;
